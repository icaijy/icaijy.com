from pathlib import Path
from django.core.management.base import BaseCommand, CommandError
from battlecode_archive.importer import import_bytes
from battlecode_archive.ingest import InvalidArchive, MAX_UPLOAD


class Command(BaseCommand):
    help = 'Import a completed Mini Battlecode result ZIP into the website database.'

    def add_arguments(self, parser):
        parser.add_argument('archive', help='ZIP generated by mbc finals or mbc export')
        parser.add_argument('--replace', action='store_true', help='overwrite an existing season')

    def handle(self, *args, **options):
        path = Path(options['archive']).expanduser()
        try:
            if path.stat().st_size > MAX_UPLOAD:
                raise InvalidArchive('Archive exceeds 80 MiB')
            season = import_bytes(path.read_bytes(), replace=options['replace'])
        except (OSError, ValueError) as exc:
            raise CommandError(str(exc)) from exc
        self.stdout.write(self.style.SUCCESS(
            f'Imported {season.slug}: {season.matches.count()} games; /battlecode/{season.slug}/'))
